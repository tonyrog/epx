/*
 *  Wayland display driver
 *
 *  - toplevel windows through xdg-shell (xdg_wm_base), protocol code is
 *    generated by wayland-scanner from c_src/xdg-shell.xml
 *  - drawing through wl_shm buffers (XRGB8888), a small pool of buffers
 *    per window (double/triple buffered), damage + commit throttled by
 *    frame callbacks, buffers are reused when released by the compositor.
 *  - pointer (motion/button/wheel), keyboard (press/release, modifiers,
 *    client side key repeat), focus and enter/leave events.
 *  - The keyboard keymap is NOT interpreted (no libxkbcommon); wl_keyboard
 *    key codes are evdev codes and are mapped with a static US layout table.
 *  - No decorations: client side decorations are not drawn and
 *    xdg-decoration (server side decorations) is not requested. On
 *    compositors without server side decorations (GNOME/mutter) the window
 *    has no title bar (use Super+drag to move it).
 *  - No output scaling (buffer scale is always 1).
 *
 *  Event loop integration: evt_attach returns an epoll fd that becomes
 *  readable when the wayland socket is readable, when the internal event
 *  queue is non empty (eventfd) or when the key repeat timer (timerfd)
 *  expires. All wayland dispatching is done in the backend thread
 *  (evt_read, window attach/adjust etc) so no locking is needed for the
 *  event queue.
 */

