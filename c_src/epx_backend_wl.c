static void wl_cleanup(WLBackend* be)
{
    if (be->cursor_surface) wl_surface_destroy(be->cursor_surface);
    if (be->cursor_theme) wl_cursor_theme_destroy(be->cursor_theme);
    if (be->pointer) wl_pointer_destroy(be->pointer);
    if (be->keyboard) wl_keyboard_destroy(be->keyboard);
    if (be->seat) wl_seat_destroy(be->seat);
    if (be->output) wl_output_destroy(be->output);
    if (be->wm_base) xdg_wm_base_destroy(be->wm_base);
    if (be->shm) wl_shm_destroy(be->shm);
    if (be->compositor) wl_compositor_destroy(be->compositor);
    if (be->registry) wl_registry_destroy(be->registry);
    if (be->display) {
	wl_display_flush(be->display);
	wl_display_disconnect(be->display);
    }
    if (be->epoll_fd >= 0) close(be->epoll_fd);
    if (be->queue_fd >= 0) close(be->queue_fd);
    if (be->timer_fd >= 0) close(be->timer_fd);
    free(be);
}

epx_backend_t* wl_init(epx_dict_t* param)
{
    WLBackend* be;
    char* display_name = NULL;
    size_t len;
    struct epoll_event ev;

    if ((be = (WLBackend*) calloc(1, sizeof(WLBackend))) == NULL)
	return NULL;
    EPX_OBJECT_INIT((epx_backend_t*)be, EPX_BACKEND_TYPE);
    be->b.on_heap = 1;
    be->b.refc = 1;
    be->b.owner = NULL;
    be->b.user = NULL;
    be->b.name = "wayland";
    be->b.pending = 0;
    be->b.opengl = 0;
    be->b.use_opengl = 0;
    be->b.width = 0;
    be->b.height = 0;
    be->b.nformats = 1;
    be->b.formats[0] = WL_EPX_FORMAT;
    epx_object_list_init(&be->b.window_list);
    epx_object_list_init(&be->b.pixmap_list);
    be->b.event = EPX_INVALID_HANDLE;
    be->b.cb = &wl_callbacks;
    be->epoll_fd = -1;
    be->queue_fd = -1;
    be->timer_fd = -1;
    be->display_fd = -1;
    be->repeat_rate = 25;
    be->repeat_delay = 600;

    if (epx_dict_lookup_string(param, "display", &display_name, &len) < 0)
	display_name = NULL;
    // "display" may be set to an X11 display name like ":0"
    if (display_name && (display_name[0] == ':'))
	display_name = NULL;

    if ((be->display = wl_display_connect(display_name)) == NULL) {
	ERRORF("wayland: unable to connect to display %s",
	       display_name ? display_name : "(default)");
	free(be);
	return NULL;
    }
    be->display_fd = wl_display_get_fd(be->display);
    be->registry = wl_display_get_registry(be->display);
    wl_registry_add_listener(be->registry, &registry_listener, be);
    wl_display_roundtrip(be->display);  // get globals
    wl_display_roundtrip(be->display);  // get seat caps, shm formats, mode

    if (!be->compositor || !be->shm || !be->wm_base) {
	ERRORF("wayland: missing globals compositor=%p shm=%p xdg_wm_base=%p",
	       be->compositor, be->shm, be->wm_base);
	wl_cleanup(be);
	return NULL;
    }

    // cursor (optional)
    {
	char* theme = getenv("XCURSOR_THEME");
	char* size_str = getenv("XCURSOR_SIZE");
	int size = size_str ? atoi(size_str) : 0;
	if (size <= 0) size = 24;
	be->cursor_theme = wl_cursor_theme_load(theme, size, be->shm);
	if (be->cursor_theme) {
	    be->cursor = wl_cursor_theme_get_cursor(be->cursor_theme,
						    "left_ptr");
	    if (!be->cursor)
		be->cursor = wl_cursor_theme_get_cursor(be->cursor_theme,
							"default");
	}
	if (be->cursor)
	    be->cursor_surface = wl_compositor_create_surface(be->compositor);
    }

    be->queue_fd = eventfd(0, EFD_NONBLOCK|EFD_CLOEXEC);
    be->timer_fd = timerfd_create(CLOCK_MONOTONIC, TFD_NONBLOCK|TFD_CLOEXEC);
    be->epoll_fd = epoll_create1(EPOLL_CLOEXEC);
    if ((be->epoll_fd < 0) || (be->queue_fd < 0)) {
	ERRORF("wayland: unable to create epoll/eventfd: %s", strerror(errno));
	wl_cleanup(be);
	return NULL;
    }
    memset(&ev, 0, sizeof(ev));
    ev.events = EPOLLIN;
    ev.data.fd = be->display_fd;
    epoll_ctl(be->epoll_fd, EPOLL_CTL_ADD, be->display_fd, &ev);
    ev.data.fd = be->queue_fd;
    epoll_ctl(be->epoll_fd, EPOLL_CTL_ADD, be->queue_fd, &ev);
    if (be->timer_fd >= 0) {
	ev.data.fd = be->timer_fd;
	epoll_ctl(be->epoll_fd, EPOLL_CTL_ADD, be->timer_fd, &ev);
    }

    wl_adjust((epx_backend_t*)be, param);
    // events may already be queued (none expected, but be safe)
    if (be->qlen > 0)
	queue_signal(be, 1);
    return (epx_backend_t*) &(be->b);
}

