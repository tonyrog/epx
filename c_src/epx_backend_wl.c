static void pointer_button(void* data, struct wl_pointer* pointer,
			   uint32_t serial, uint32_t time, uint32_t button,
			   uint32_t state)
{
    WLBackend* b = (WLBackend*) data;
    uint32_t bit;
    (void) pointer;
    (void) serial;
    (void) time;

    switch(button) {
    case BTN_LEFT:   bit = EPX_BUTTON_LEFT; break;
    case BTN_MIDDLE: bit = EPX_BUTTON_MIDDLE; break;
    case BTN_RIGHT:  bit = EPX_BUTTON_RIGHT; break;
    default: return;
    }
    if (state == WL_POINTER_BUTTON_STATE_PRESSED) {
	b->buttons |= bit;
	if (b->pointer_win)
	    queue_pointer(b->pointer_win, EPX_EVENT_BUTTON_PRESS, bit);
    }
    else {
	b->buttons &= ~bit;
	if (b->pointer_win)
	    queue_pointer(b->pointer_win, EPX_EVENT_BUTTON_RELEASE, bit);
    }
}

static void wheel_steps(WLBackend* b, uint32_t axis, int steps)
{
    uint32_t bit;
    if (!b->pointer_win || (steps == 0))
	return;
    if (axis == WL_POINTER_AXIS_VERTICAL_SCROLL)
	bit = (steps > 0) ? EPX_WHEEL_DOWN : EPX_WHEEL_UP;
    else
	bit = (steps > 0) ? EPX_WHEEL_RIGHT : EPX_WHEEL_LEFT;
    if (steps < 0) steps = -steps;
    if (steps > 10) steps = 10;
    while(steps--) {  // like X11, wheel is a button press/release pair
	queue_pointer(b->pointer_win, EPX_EVENT_BUTTON_PRESS, bit);
	queue_pointer(b->pointer_win, EPX_EVENT_BUTTON_RELEASE, bit);
    }
}

#define WL_AXIS_STEP 10.0

static void pointer_axis(void* data, struct wl_pointer* pointer,
			 uint32_t time, uint32_t axis, wl_fixed_t value)
{
    WLBackend* b = (WLBackend*) data;
    int i = (axis == WL_POINTER_AXIS_VERTICAL_SCROLL) ? 0 : 1;
    int steps = 0;
    (void) pointer;
    (void) time;

    if (axis > WL_POINTER_AXIS_HORIZONTAL_SCROLL)
	return;
    if (b->axis_discrete[i]) {  // discrete steps already given
	steps = b->axis_discrete[i];
	b->axis_discrete[i] = 0;
	b->axis_acc[i] = 0.0;
    }
    else {
	b->axis_acc[i] += wl_fixed_to_double(value);
	while (b->axis_acc[i] >= WL_AXIS_STEP) {
	    steps++;
	    b->axis_acc[i] -= WL_AXIS_STEP;
	}
	while (b->axis_acc[i] <= -WL_AXIS_STEP) {
	    steps--;
	    b->axis_acc[i] += WL_AXIS_STEP;
	}
    }
    wheel_steps(b, axis, steps);
}

