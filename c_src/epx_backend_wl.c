static int wl_finish(epx_backend_t* backend)
{
    WLBackend* b = (WLBackend*) backend;
    epx_window_t* window;

    // detach windows still attached
    while((window = (epx_window_t*) b->b.window_list.first) != NULL) {
	wl_window_detach(backend, window);
	if (window == (epx_window_t*) b->b.window_list.first)
	    break;  // not unlinked ?!
    }
    // detach pixmaps
    {
	epx_pixmap_t* pixmap;
	while((pixmap = (epx_pixmap_t*) b->b.pixmap_list.first) != NULL) {
	    wl_pixmap_detach(backend, pixmap);
	    if (pixmap == (epx_pixmap_t*) b->b.pixmap_list.first)
		break;
	}
    }
    wl_cleanup(b);
    return 0;
}

static int wl_pixmap_attach(epx_backend_t* backend, epx_pixmap_t* pixmap)
{
    if (pixmap->opaque != NULL)
	return -1;
    // nothing to allocate, pixels are copied into shm buffers when drawn
    pixmap->opaque = (void*) 1;
    epx_object_link(&backend->pixmap_list, pixmap);
    pixmap->backend = backend;
    return 0;
}

static int wl_pixmap_detach(epx_backend_t* backend, epx_pixmap_t* pixmap)
{
    if (pixmap->opaque != NULL) {
	epx_object_unlink(&backend->pixmap_list, pixmap);
	pixmap->opaque = NULL;
	pixmap->backend = NULL;
    }
    return 0;
}

