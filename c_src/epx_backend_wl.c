// US layout: evdev code -> (unshifted, shifted) ascii
static const char keymap_us[][2] = {
    [KEY_1] = {'1','!'}, [KEY_2] = {'2','@'}, [KEY_3] = {'3','#'},
    [KEY_4] = {'4','$'}, [KEY_5] = {'5','%'}, [KEY_6] = {'6','^'},
    [KEY_7] = {'7','&'}, [KEY_8] = {'8','*'}, [KEY_9] = {'9','('},
    [KEY_0] = {'0',')'}, [KEY_MINUS] = {'-','_'}, [KEY_EQUAL] = {'=','+'},
    [KEY_Q] = {'q','Q'}, [KEY_W] = {'w','W'}, [KEY_E] = {'e','E'},
    [KEY_R] = {'r','R'}, [KEY_T] = {'t','T'}, [KEY_Y] = {'y','Y'},
    [KEY_U] = {'u','U'}, [KEY_I] = {'i','I'}, [KEY_O] = {'o','O'},
    [KEY_P] = {'p','P'}, [KEY_LEFTBRACE] = {'[','{'},
    [KEY_RIGHTBRACE] = {']','}'},
    [KEY_A] = {'a','A'}, [KEY_S] = {'s','S'}, [KEY_D] = {'d','D'},
    [KEY_F] = {'f','F'}, [KEY_G] = {'g','G'}, [KEY_H] = {'h','H'},
    [KEY_J] = {'j','J'}, [KEY_K] = {'k','K'}, [KEY_L] = {'l','L'},
    [KEY_SEMICOLON] = {';',':'}, [KEY_APOSTROPHE] = {'\'','"'},
    [KEY_GRAVE] = {'`','~'}, [KEY_BACKSLASH] = {'\\','|'},
    [KEY_Z] = {'z','Z'}, [KEY_X] = {'x','X'}, [KEY_C] = {'c','C'},
    [KEY_V] = {'v','V'}, [KEY_B] = {'b','B'}, [KEY_N] = {'n','N'},
    [KEY_M] = {'m','M'}, [KEY_COMMA] = {',','<'}, [KEY_DOT] = {'.','>'},
    [KEY_SLASH] = {'/','?'}, [KEY_SPACE] = {' ',' '},
    [KEY_102ND] = {'<','>'},
};

#define KEYMAP_US_SIZE ((int)(sizeof(keymap_us)/sizeof(keymap_us[0])))

static int is_modifier_key(uint32_t key)
{
    switch(key) {
    case KEY_LEFTSHIFT: case KEY_RIGHTSHIFT:
    case KEY_LEFTCTRL: case KEY_RIGHTCTRL:
    case KEY_LEFTALT: case KEY_RIGHTALT:
    case KEY_LEFTMETA: case KEY_RIGHTMETA:
    case KEY_CAPSLOCK: case KEY_NUMLOCK: case KEY_SCROLLLOCK:
	return 1;
    default:
	return 0;
    }
}

static void modify(WLBackend* b, int pressed, unsigned short mod)
{
    if (pressed)
	b->modstate |= mod;
    else
	b->modstate &= ~mod;
}

// translate evdev key into epx key event
// return 0 if no event should be generated
static int translate_key(WLBackend* b, uint32_t key, int pressed,
			 epx_event_t* e)
{
    uint16_t sym = 0;

    switch(key) {
    case KEY_ESC:       sym = EPX_KBD_KEY_ESCAPE; break;
    case KEY_BACKSPACE: sym = EPX_KBD_KEY_BACKSPACE; break;
    case KEY_TAB:       sym = EPX_KBD_KEY_TAB; break;
    case KEY_ENTER:     sym = EPX_KBD_KEY_ENTER; break;
    case KEY_DELETE:    sym = EPX_KBD_KEY_DELETE; break;
    case KEY_HOME:      sym = EPX_KBD_KEY_HOME; break;
    case KEY_LEFT:      sym = EPX_KBD_KEY_LEFT; break;
    case KEY_UP:        sym = EPX_KBD_KEY_UP; break;
    case KEY_RIGHT:     sym = EPX_KBD_KEY_RIGHT; break;
    case KEY_DOWN:      sym = EPX_KBD_KEY_DOWN; break;
    case KEY_PAGEUP:    sym = EPX_KBD_KEY_PAGEUP; break;
    case KEY_PAGEDOWN:  sym = EPX_KBD_KEY_PAGEDOWN; break;
    case KEY_END:       sym = EPX_KBD_KEY_END; break;
    case KEY_INSERT:    sym = EPX_KBD_KEY_INSERT; break;
    case KEY_PAUSE:
    case KEY_BREAK:     sym = EPX_KBD_KEY_QUIT; break;
    case KEY_PRINT:
    case KEY_SYSRQ:     sym = EPX_KBD_KEY_PRINT; break;
    case KEY_COMPOSE:
    case KEY_MENU:      sym = EPX_KBD_KEY_MENU; break;
    case KEY_CANCEL:    sym = EPX_KBD_KEY_CANCEL; break;
    case KEY_KPENTER:   sym = EPX_KBD_KEY_KP_ENTER; break;
    case KEY_KP7:       sym = EPX_KBD_KEY_KP7; break;
    case KEY_KP4:       sym = EPX_KBD_KEY_KP4; break;
    case KEY_KP8:       sym = EPX_KBD_KEY_KP8; break;
    case KEY_KP6:       sym = EPX_KBD_KEY_KP6; break;
    case KEY_KP2:       sym = EPX_KBD_KEY_KP2; break;
    case KEY_KP9:       sym = EPX_KBD_KEY_KP9; break;
    case KEY_KP3:       sym = EPX_KBD_KEY_KP3; break;
    case KEY_KP1:       sym = EPX_KBD_KEY_KP1; break;
    case KEY_KP0:       sym = EPX_KBD_KEY_KP0; break;
    case KEY_KP5:       sym = EPX_KBD_KEY_KP5; break;
    case KEY_KPDOT:     sym = EPX_KBD_KEY_KP_PERIOD; break;
    case KEY_KPEQUAL:   sym = EPX_KBD_KEY_KP_EQUALS; break;
    case KEY_KPASTERISK: sym = EPX_KBD_KEY_KP_MULTIPLY; break;
    case KEY_KPPLUS:    sym = EPX_KBD_KEY_KP_PLUS; break;
    case KEY_KPMINUS:   sym = EPX_KBD_KEY_KP_MINUS; break;
    case KEY_KPSLASH:   sym = EPX_KBD_KEY_KP_DIVIDE; break;
    case KEY_F1:  sym = EPX_KBD_KEY_F1;  break;
    case KEY_F2:  sym = EPX_KBD_KEY_F2;  break;
    case KEY_F3:  sym = EPX_KBD_KEY_F3;  break;
    case KEY_F4:  sym = EPX_KBD_KEY_F4;  break;
    case KEY_F5:  sym = EPX_KBD_KEY_F5;  break;
    case KEY_F6:  sym = EPX_KBD_KEY_F6;  break;
    case KEY_F7:  sym = EPX_KBD_KEY_F7;  break;
    case KEY_F8:  sym = EPX_KBD_KEY_F8;  break;
    case KEY_F9:  sym = EPX_KBD_KEY_F9;  break;
    case KEY_F10: sym = EPX_KBD_KEY_F10; break;
    case KEY_F11: sym = EPX_KBD_KEY_F11; break;
    case KEY_F12: sym = EPX_KBD_KEY_F12; break;
	// state modifiers, not sent (like x11), locks are updated
	// from wl_keyboard.modifiers
    case KEY_NUMLOCK:
    case KEY_CAPSLOCK:
	return 0;
    case KEY_SCROLLLOCK:
	if (pressed) b->modstate ^= EPX_KBD_MOD_SCR;
	return 0;
    case KEY_LEFTSHIFT:
	sym = EPX_KBD_KEY_LSHIFT; modify(b, pressed, EPX_KBD_MOD_LSHIFT); break;
    case KEY_RIGHTSHIFT:
	sym = EPX_KBD_KEY_RSHIFT; modify(b, pressed, EPX_KBD_MOD_RSHIFT); break;
    case KEY_LEFTCTRL:
	sym = EPX_KBD_KEY_LCTRL; modify(b, pressed, EPX_KBD_MOD_LCTRL); break;
    case KEY_RIGHTCTRL:
	sym = EPX_KBD_KEY_RCTRL; modify(b, pressed, EPX_KBD_MOD_RCTRL); break;
    case KEY_LEFTALT:
	sym = EPX_KBD_KEY_LALT; modify(b, pressed, EPX_KBD_MOD_LALT); break;
    case KEY_RIGHTALT:
	sym = EPX_KBD_KEY_RALT; modify(b, pressed, EPX_KBD_MOD_RALT); break;
    case KEY_LEFTMETA:
	sym = EPX_KBD_KEY_LMETA; modify(b, pressed, EPX_KBD_MOD_LMETA); break;
    case KEY_RIGHTMETA:
	sym = EPX_KBD_KEY_RMETA; modify(b, pressed, EPX_KBD_MOD_RMETA); break;
    default:
	if (((int)key < KEYMAP_US_SIZE) && keymap_us[key][0]) {
	    int shift = (b->modstate & EPX_KBD_MOD_SHIFT) != 0;
	    char c0 = keymap_us[key][0];
	    if ((c0 >= 'a') && (c0 <= 'z') && (b->modstate & EPX_KBD_MOD_CAPS))
		shift = !shift;
	    sym = (uint8_t) keymap_us[key][shift];
	    if (b->modstate & EPX_KBD_MOD_CTRL)
		sym = sym & 0x1f;	/* Control code */
	}
	else {
	    EPX_DBGFMT("wayland: unhandled key code %u", key);
	    return 0;
	}
	break;
    }

    if (b->modstate & EPX_KBD_MOD_NUM) {
	switch (sym) {
	case EPX_KBD_KEY_KP0: case EPX_KBD_KEY_KP1: case EPX_KBD_KEY_KP2:
	case EPX_KBD_KEY_KP3: case EPX_KBD_KEY_KP4: case EPX_KBD_KEY_KP5:
	case EPX_KBD_KEY_KP6: case EPX_KBD_KEY_KP7: case EPX_KBD_KEY_KP8:
	case EPX_KBD_KEY_KP9:
	    sym = (sym - EPX_KBD_KEY_KP0) + '0';
	    break;
	case EPX_KBD_KEY_KP_PERIOD: sym = '.'; break;
	case EPX_KBD_KEY_KP_DIVIDE: sym = '/'; break;
	case EPX_KBD_KEY_KP_MULTIPLY: sym = '*'; break;
	case EPX_KBD_KEY_KP_MINUS: sym = '-'; break;
	case EPX_KBD_KEY_KP_PLUS:  sym = '+'; break;
	case EPX_KBD_KEY_KP_ENTER: sym = EPX_KBD_KEY_ENTER; break;
	case EPX_KBD_KEY_KP_EQUALS: sym = '='; break;
	default: break;
	}
    }
    e->type = pressed ? EPX_EVENT_KEY_PRESS : EPX_EVENT_KEY_RELEASE;
    e->key.sym  = sym;
    e->key.code = key + 8;   // X11 compatible key code
    e->key.mod  = b->modstate;
    return 1;
}

static void repeat_stop(WLBackend* b)
{
    struct itimerspec its;
    b->repeat_key = 0;
    if (b->timer_fd < 0)
	return;
    memset(&its, 0, sizeof(its));
    timerfd_settime(b->timer_fd, 0, &its, NULL);
}

static void repeat_start(WLBackend* b, uint32_t key)
{
    struct itimerspec its;
    long interval_ns;

    if ((b->timer_fd < 0) || (b->repeat_rate <= 0))
	return;
    b->repeat_key = key;
    interval_ns = 1000000000L / b->repeat_rate;
    its.it_value.tv_sec  = b->repeat_delay / 1000;
    its.it_value.tv_nsec = (b->repeat_delay % 1000) * 1000000L;
    if ((its.it_value.tv_sec == 0) && (its.it_value.tv_nsec == 0))
	its.it_value.tv_nsec = 1;
    its.it_interval.tv_sec  = interval_ns / 1000000000L;
    its.it_interval.tv_nsec = interval_ns % 1000000000L;
    timerfd_settime(b->timer_fd, 0, &its, NULL);
}

static void repeat_expired(WLBackend* b)
{
    uint64_t n = 0;
    epx_event_t e;
    WLWindow* w = b->kbd_win;

    if (b->timer_fd < 0)
	return;
    if (read(b->timer_fd, &n, sizeof(n)) != sizeof(n))
	return;
    if ((b->repeat_key == 0) || (w == NULL))
	return;
    if (n > 4) n = 4;
    while(n--) {
	// X11 style auto repeat, release + press
	memset(&e, 0, sizeof(e));
	e.window = w->ewin;
	if (translate_key(b, b->repeat_key, 0, &e))
	    queue_put(b, &e);
	memset(&e, 0, sizeof(e));
	e.window = w->ewin;
	if (translate_key(b, b->repeat_key, 1, &e))
	    queue_put(b, &e);
    }
}

