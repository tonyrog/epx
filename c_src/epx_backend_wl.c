static int wl_draw(epx_backend_t* backend, epx_pixmap_t* pixmap,
		   epx_window_t* window,
		   int src_x, int src_y, int dst_x, int dst_y,
		   unsigned int width,
		   unsigned int height)
{
    WLWindow* w = (WLWindow*) window->opaque;
    WLBuffer* bp;
    epx_rect_t sr, dr;
    int dx, dy;
    (void) backend;

    if ((w == NULL) || (pixmap == NULL) || (pixmap->data == NULL))
	return -1;
    if ((bp = get_back_buffer(w)) == NULL)
	return -1;

    // clip source against pixmap
    epx_rect_set(&sr, src_x, src_y, width, height);
    epx_rect_set(&dr, 0, 0, pixmap->width, pixmap->height);
    if (!epx_rect_intersect(&sr, &dr, &sr))
	return 0;
    dst_x += (sr.xy.x - src_x);
    dst_y += (sr.xy.y - src_y);
    // clip destination against buffer
    epx_rect_set(&dr, dst_x, dst_y, sr.wh.width, sr.wh.height);
    {
	epx_rect_t br;
	epx_rect_set(&br, 0, 0, bp->width, bp->height);
	if (!epx_rect_intersect(&dr, &br, &dr))
	    return 0;
    }
    dx = dr.xy.x - dst_x;
    dy = dr.xy.y - dst_y;

    epx_copy_area(pixmap->data
		  + (sr.xy.y+dy)*pixmap->bytes_per_row
		  + (sr.xy.x+dx)*pixmap->bytes_per_pixel,
		  pixmap->bytes_per_row, pixmap->pixel_format,
		  bp->data + dr.xy.y*bp->stride + dr.xy.x*4,
		  bp->stride, WL_EPX_FORMAT,
		  dr.wh.width, dr.wh.height);
    add_damage(w, dr.xy.x, dr.xy.y, dr.wh.width, dr.wh.height);
    return 0;
}

// make sure all draw commands have been synced
static int wl_pixmap_sync(epx_backend_t* backend, epx_pixmap_t* pixmap,
			  epx_window_t* window)
{
    WLBackend* b = (WLBackend*) backend;
    (void) pixmap;

    if (window && window->opaque)
	window_swap((WLWindow*) window->opaque);
    if (!b->dead) {
	wl_display_flush(b->display);
	wl_display_roundtrip(b->display);
    }
    return 0;
}

static int wl_window_swap(epx_backend_t* backend, epx_window_t* window)
{
    WLBackend* b = (WLBackend*) backend;
    WLWindow* w = (WLWindow*) window->opaque;

    if (w == NULL)
	return -1;
    window_swap(w);
    wl_display_flush(b->display);
    backend->pending = b->qlen;
    return 0;
}

// map the window (initial commit, wait for configure, attach buffer)
static int window_map(WLBackend* be, WLWindow* w)
{
    int i;

    w->configured = 0;
    w->mapped = 0;
    wl_surface_attach(w->surface, NULL, 0, 0);
    wl_surface_commit(w->surface);
    for (i = 0; (i < 100) && !w->configured; i++) {
	if (wl_display_roundtrip(be->display) < 0)
	    break;
    }
    if (!w->configured) {
	ERRORF("wayland: window not configured");
	return -1;
    }
    if (get_back_buffer(w) == NULL)
	return -1;
    do_commit(w);
    return 0;
}

static int wl_window_attach(epx_backend_t* backend, epx_window_t* window)
{
    WLBackend* be = (WLBackend*) backend;
    WLWindow* w;

    if (window->opaque != NULL)
	return -1;
    if (be->dead)
	return -1;
    if ((w = (WLWindow*) calloc(1, sizeof(WLWindow))) == NULL)
	return -1;
    w->be = be;
    w->ewin = window;
    w->back = -1;
    w->front = -1;
    w->width  = window->area.wh.width  ? (int) window->area.wh.width  : 320;
    w->height = window->area.wh.height ? (int) window->area.wh.height : 240;
    epx_rect_empty(&w->dirty);

    w->surface  = wl_compositor_create_surface(be->compositor);
    w->xsurface = xdg_wm_base_get_xdg_surface(be->wm_base, w->surface);
    xdg_surface_add_listener(w->xsurface, &xsurface_listener, w);
    w->toplevel = xdg_surface_get_toplevel(w->xsurface);
    xdg_toplevel_add_listener(w->toplevel, &toplevel_listener, w);
    xdg_toplevel_set_title(w->toplevel, "epx");
    xdg_toplevel_set_app_id(w->toplevel, "epx");

    // link before roundtrip so input events find the window
    window->opaque  = (void*) w;
    window->backend = (epx_backend_t*) be;
    epx_object_link(&backend->window_list, window);

    if (window_map(be, w) < 0) {
	wl_window_detach(backend, window);
	return -1;
    }
    return 0;
}

static int wl_window_detach(epx_backend_t* backend, epx_window_t* window)
{
    WLBackend* be = (WLBackend*) backend;
    WLWindow*  w = (WLWindow*) window->opaque;
    int i;

    if (w == NULL)
	return -1;
    queue_purge(be, window);
    if (be->pointer_win == w) be->pointer_win = NULL;
    if (be->kbd_win == w) {
	be->kbd_win = NULL;
	repeat_stop(be);
    }
    if (w->frame_cb) wl_callback_destroy(w->frame_cb);
    for (i = 0; i < WL_MAX_BUFFERS; i++)
	buffer_destroy(&w->buf[i]);
    if (w->toplevel) xdg_toplevel_destroy(w->toplevel);
    if (w->xsurface) xdg_surface_destroy(w->xsurface);
    if (w->surface)  wl_surface_destroy(w->surface);
    wl_display_flush(be->display);
    free(w->title);
    free(w);
    epx_object_unlink(&backend->window_list, window);
    window->opaque  = NULL;
    window->backend = NULL;
    return 0;
}

// read and dispatch wayland events without blocking
static void wl_pump(WLBackend* b)
{
    struct pollfd pfd;

    repeat_expired(b);
    if (b->dead)
	return;
    while (wl_display_prepare_read(b->display) != 0) {
	if (wl_display_dispatch_pending(b->display) < 0)
	    goto error;
    }
    wl_display_flush(b->display);
    pfd.fd = b->display_fd;
    pfd.events = POLLIN;
    pfd.revents = 0;
    if ((poll(&pfd, 1, 0) > 0) && (pfd.revents & (POLLIN|POLLHUP|POLLERR))) {
	if (wl_display_read_events(b->display) < 0)
	    goto error;
    }
    else
	wl_display_cancel_read(b->display);
    if (wl_display_dispatch_pending(b->display) < 0)
	goto error;
    wl_display_flush(b->display);
    return;
error:
    {
	int err = wl_display_get_error(b->display);
	ERRORF("wayland: display error %d (%s)", err, strerror(err));
	if (err == EPROTO) {
	    const struct wl_interface* iface;
	    uint32_t id;
	    uint32_t code = wl_display_get_protocol_error(b->display,
							  &iface, &id);
	    ERRORF("wayland: protocol error %u on %s@%u", code,
		   iface ? iface->name : "?", id);
	}
	fprintf(stderr, "epx: wayland display error %d (%s)\r\n",
		err, strerror(err));
    }
    b->dead = 1;
    epoll_ctl(b->epoll_fd, EPOLL_CTL_DEL, b->display_fd, NULL);
}

static int filter_event(epx_event_t* e)
{
    uint32_t mask;

    if (!e->window)
	return 1;
    if (e->type == EPX_EVENT_CLOSE)
	return 0;
    mask = e->window->mask;
    if ((e->type & mask) == 0)
	return 1;
    switch(e->type) {
    case EPX_EVENT_BUTTON_PRESS:
    case EPX_EVENT_BUTTON_RELEASE:
    case EPX_EVENT_POINTER_MOTION:
	mask &= EPX_EVENT_BUTTON_MASK; // only button events
	if (mask == EPX_EVENT_BUTTON_ANY)
	    return 0;
	if ((e->pointer.button & (mask >> 16)) == 0)
	    return 1;
	break;
    default:
	break;
    }
    return 0;
}

/* return -1: error in event processing
 *         0: no event returned  & no pending
 *         1: one event returned & no pending
 *         2: one event returned & 1 pending
 *         and so on
 */
static int wl_evt_read(epx_backend_t* backend, epx_event_t* e)
{
    WLBackend* b = (WLBackend*) backend;

    backend->pending = 0;
    if (b->qlen == 0)
	wl_pump(b);
    while (queue_get(b, e)) {
	if (filter_event(e))
	    continue;
	backend->pending = b->qlen;
	return 1 + b->qlen;
    }
    return 0;
}

