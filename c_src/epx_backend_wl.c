static int wl_info(epx_backend_t* backend, epx_dict_t*param)
{
    WLBackend* b  = (WLBackend*) backend;
    int bval;

    if (epx_dict_lookup_boolean(param, "display", &bval) >= 0) {
	epx_dict_set_binary(param, "display", &b->display,
			    sizeof(struct wl_display*));
    }
    if (epx_dict_lookup_boolean(param, "double_buffer", &bval) != -1) {
	epx_dict_set_boolean(param, "double_buffer", 1);
    }
    if (epx_dict_lookup_boolean(param, "use_exposure", &bval) != -1) {
	epx_dict_set_boolean(param, "use_exposure", 0);
    }
    if (epx_dict_lookup_boolean(param, "use_opengl", &bval) != -1) {
	epx_dict_set_boolean(param, "use_opengl", 0);
    }
    return 1;
}

static int wl_window_adjust(epx_window_t *win, epx_dict_t*param)
{
    WLWindow*  w  = (WLWindow*) win->opaque;
    WLBackend* b;
    char* window_name = NULL;
    size_t name_len;
    int bool_val;
    int min_w = -1, min_h = -1, max_w = -1, max_h = -1;
    int width = -1, height = -1;
    int ival;

    if (w == NULL)
	return -1;
    b = w->be;

    if (epx_dict_lookup_string(param, "name", &window_name, &name_len) >= 0) {
	char* title = malloc(name_len+1);
	if (title) {
	    memcpy(title, window_name, name_len);
	    title[name_len] = '\0';
	    free(w->title);
	    w->title = title;
	    xdg_toplevel_set_title(w->toplevel, title);
	}
    }
    epx_dict_lookup_integer(param, "min_width", &min_w);
    epx_dict_lookup_integer(param, "min_height", &min_h);
    epx_dict_lookup_integer(param, "max_width", &max_w);
    epx_dict_lookup_integer(param, "max_height", &max_h);
    if ((min_w >= 0) || (min_h >= 0))
	xdg_toplevel_set_min_size(w->toplevel,
				  (min_w < 0) ? 0 : min_w,
				  (min_h < 0) ? 0 : min_h);
    if ((max_w >= 0) || (max_h >= 0))
	xdg_toplevel_set_max_size(w->toplevel,
				  (max_w < 0) ? 0 : max_w,
				  (max_h < 0) ? 0 : max_h);

    // x,y: clients can not position toplevels in wayland, only record
    if (epx_dict_lookup_integer(param, "x", &ival) >= 0)
	win->area.xy.x = ival;
    if (epx_dict_lookup_integer(param, "y", &ival) >= 0)
	win->area.xy.y = ival;
    epx_dict_lookup_integer(param, "width", &width);
    epx_dict_lookup_integer(param, "height", &height);
    if ((width > 0) || (height > 0)) {
	if (width <= 0) width = w->width;
	if (height <= 0) height = w->height;
	if ((width != w->width) || (height != w->height)) {
	    // floating toplevels may change size by attaching a new buffer
	    window_resize(w, width, height);
	    queue_configure(w);
	    window_swap(w);
	}
    }

    if (epx_dict_lookup_boolean(param, "show", &bool_val) >= 0) {
	if (!bool_val && !w->hidden) {
	    w->hidden = 1;
	    wl_surface_attach(w->surface, NULL, 0, 0);
	    wl_surface_commit(w->surface);
	    w->mapped = 0;
	}
	else if (bool_val && w->hidden) {
	    w->hidden = 0;
	    window_map(b, w);
	}
    }
    if (epx_dict_lookup_boolean(param, "select", &bool_val) >= 0) {
	// activation requires xdg-activation, not supported
    }
    wl_display_flush(b->display);
    return 1;
}

// Query interface, send boolean entries and return the
// queried for value
static int wl_window_info(epx_window_t* win, epx_dict_t* param)
{
    int bval;
    WLWindow*  w  = (WLWindow*) win->opaque;

    if (w == NULL)
	return -1;
    if (epx_dict_lookup_boolean(param, "name", &bval) >= 0) {
	epx_dict_set_string(param, "name", w->title ? w->title : "");
    }
    if (epx_dict_lookup_boolean(param, "display", &bval) >= 0) {
	epx_dict_set_binary(param, "display", &w->be->display,
			    sizeof(struct wl_display*));
    }
    if (epx_dict_lookup_boolean(param, "window", &bval) >= 0) {
	epx_dict_set_binary(param, "window", &w->surface,
			    sizeof(struct wl_surface*));
    }
    return 1;
}
