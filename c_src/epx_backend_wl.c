#define MIN_VERSION(a,b) (((a) < (b)) ? (a) : (b))

static void registry_global(void* data, struct wl_registry* registry,
			    uint32_t name, const char* interface,
			    uint32_t version)
{
    WLBackend* b = (WLBackend*) data;

    EPX_DBGFMT("wayland: global %s version %u", interface, version);
    if (strcmp(interface, wl_compositor_interface.name) == 0) {
	b->compositor_version = MIN_VERSION(version, 4);
	b->compositor = wl_registry_bind(registry, name,
					 &wl_compositor_interface,
					 b->compositor_version);
    }
    else if (strcmp(interface, wl_shm_interface.name) == 0) {
	b->shm = wl_registry_bind(registry, name, &wl_shm_interface, 1);
	wl_shm_add_listener(b->shm, &shm_listener, b);
    }
    else if (strcmp(interface, xdg_wm_base_interface.name) == 0) {
	b->wm_base = wl_registry_bind(registry, name,
				      &xdg_wm_base_interface, 1);
	xdg_wm_base_add_listener(b->wm_base, &wm_base_listener, b);
    }
    else if ((strcmp(interface, wl_seat_interface.name) == 0) && !b->seat) {
	b->seat = wl_registry_bind(registry, name, &wl_seat_interface,
				   MIN_VERSION(version, 5));
	wl_seat_add_listener(b->seat, &seat_listener, b);
    }
    else if ((strcmp(interface, wl_output_interface.name) == 0) &&
	     !b->output) {
	b->output = wl_registry_bind(registry, name, &wl_output_interface,
				     MIN_VERSION(version, 2));
	wl_output_add_listener(b->output, &output_listener, b);
    }
}

