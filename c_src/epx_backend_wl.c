static void xsurface_configure(void* data, struct xdg_surface* xsurface,
			       uint32_t serial)
{
    WLWindow* w = (WLWindow*) data;
    int first = !w->configured;
    int width  = w->width;
    int height = w->height;

    // The configure size is a suggestion for floating windows. It is
    // only followed when the window is maximized/fullscreen/tiled/being
    // resized interactively or when leaving such a state, otherwise a
    // stale suggestion could undo a client resize (window_adjust).
    if (w->cfg_forced || w->was_forced || first) {
	if (w->cfg_width > 0)  width  = w->cfg_width;
	if (w->cfg_height > 0) height = w->cfg_height;
    }
    w->was_forced = w->cfg_forced;

    EPX_DBGFMT("wayland: xdg_surface.configure serial=%u size=%dx%d",
	       serial, width, height);
    xdg_surface_ack_configure(xsurface, serial);
    w->configured = 1;

    if ((width != w->width) || (height != w->height)) {
	window_resize(w, width, height);
	queue_configure(w);
	window_swap(w);
    }
    else if (first) {
	queue_configure(w);
    }
    if (first) {
	epx_event_t e;
	memset(&e, 0, sizeof(e));
	e.type = EPX_EVENT_EXPOSE;
	e.window = w->ewin;
	e.area.w = w->width;
	e.area.h = w->height;
	queue_put(w->be, &e);
    }
}

