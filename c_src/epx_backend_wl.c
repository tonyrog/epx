/******************************************************************************
 *  Event queue
 *****************************************************************************/

static void queue_signal(WLBackend* b, int non_empty)
{
    uint64_t v = 1;
    ssize_t r;
    if (b->queue_fd < 0)
	return;
    if (non_empty)
	r = write(b->queue_fd, &v, sizeof(v));
    else
	r = read(b->queue_fd, &v, sizeof(v));
    (void) r;
}

static void queue_put(WLBackend* b, epx_event_t* e)
{
    if (e->window == NULL)
	return;
    if (b->qlen >= WL_EVENT_QUEUE_SIZE) {
	WARNINGF("wayland: event queue full, dropping event %x", e->type);
	return;
    }
    b->queue[(b->qhead + b->qlen) % WL_EVENT_QUEUE_SIZE] = *e;
    b->qlen++;
    if (b->qlen == 1)
	queue_signal(b, 1);
}

static int queue_get(WLBackend* b, epx_event_t* e)
{
    if (b->qlen == 0)
	return 0;
    *e = b->queue[b->qhead];
    b->qhead = (b->qhead + 1) % WL_EVENT_QUEUE_SIZE;
    b->qlen--;
    if (b->qlen == 0)
	queue_signal(b, 0);
    return 1;
}

// remove all queued events for a window (window is being detached)
static void queue_purge(WLBackend* b, epx_window_t* window)
{
    unsigned i, n = b->qlen;
    unsigned j = 0;
    epx_event_t tmp;

    for (i = 0; i < n; i++) {
	tmp = b->queue[(b->qhead + i) % WL_EVENT_QUEUE_SIZE];
	if (tmp.window != window)
	    b->queue[(b->qhead + j++) % WL_EVENT_QUEUE_SIZE] = tmp;
    }
    b->qlen = j;
    if ((n > 0) && (j == 0))
	queue_signal(b, 0);
}

static void queue_simple(WLWindow* w, uint32_t type)
{
    epx_event_t e;
    memset(&e, 0, sizeof(e));
    e.type = type;
    e.window = w->ewin;
    queue_put(w->be, &e);
}

static void queue_pointer(WLWindow* w, uint32_t type, uint32_t button)
{
    epx_event_t e;
    memset(&e, 0, sizeof(e));
    e.type = type;
    e.window = w->ewin;
    e.pointer.button = button;
    e.pointer.x = w->be->px;
    e.pointer.y = w->be->py;
    e.pointer.z = 0;
    queue_put(w->be, &e);
}

static void queue_configure(WLWindow* w)
{
    epx_event_t e;
    memset(&e, 0, sizeof(e));
    e.type = EPX_EVENT_CONFIGURE;
    e.window = w->ewin;
    e.area.x = w->ewin->area.xy.x;
    e.area.y = w->ewin->area.xy.y;
    e.area.w = w->width;
    e.area.h = w->height;
    w->ewin->rarea.xy.x = e.area.x;
    w->ewin->rarea.xy.y = e.area.y;
    w->ewin->rarea.wh.width = w->width;
    w->ewin->rarea.wh.height = w->height;
    queue_put(w->be, &e);
}

// find the epx window that has the wl_surface (NULL if not ours)
static WLWindow* find_window(WLBackend* b, struct wl_surface* surface)
{
    epx_window_t* window;
    WLWindow* found = NULL;

    if (surface == NULL)
	return NULL;
    epx_lock_lock(b->b.window_list.lock);
    window = (epx_window_t*) b->b.window_list.first;
    while(window) {
	WLWindow* w = (WLWindow*) window->opaque;
	if (w && (w->surface == surface)) {
	    found = w;
	    break;
	}
	window = window->next;
    }
    epx_lock_unlock(b->b.window_list.lock);
    return found;
}

/******************************************************************************
 *  shm buffers
 *****************************************************************************/

static void buffer_release(void* data, struct wl_buffer* wl_buffer);

static const struct wl_buffer_listener buffer_listener = {
    .release = buffer_release
};

static void buffer_destroy(WLBuffer* bp)
{
    if (bp->buffer)
	wl_buffer_destroy(bp->buffer);
    if (bp->data)
	munmap(bp->data, bp->size);
    bp->buffer = NULL;
    bp->data = NULL;
    bp->size = 0;
    bp->busy = 0;
    bp->stale = 0;
    bp->width = bp->height = bp->stride = 0;
}

static void buffer_release(void* data, struct wl_buffer* wl_buffer)
{
    WLBuffer* bp = (WLBuffer*) data;
    (void) wl_buffer;
    bp->busy = 0;
    if (bp->stale) {
	WLWindow* w = bp->win;
	int i = bp - w->buf;
	buffer_destroy(bp);
	if (w->front == i) w->front = -1;
	if (w->back == i) w->back = -1;
    }
}

static int create_shm_file(size_t size)
{
    int fd;
#ifdef MFD_CLOEXEC
    fd = memfd_create("epx-wayland", MFD_CLOEXEC);
#else
    fd = -1;
#endif
    if (fd < 0) {
	char name[64];
	snprintf(name, sizeof(name), "/epx-wayland-%d-%p", getpid(),
		 (void*)&size);
	fd = shm_open(name, O_RDWR|O_CREAT|O_EXCL, 0600);
	if (fd < 0)
	    return -1;
	shm_unlink(name);
    }
    while (ftruncate(fd, size) < 0) {
	if (errno == EINTR) continue;
	close(fd);
	return -1;
    }
    return fd;
}

static int buffer_create(WLWindow* w, WLBuffer* bp, int width, int height)
{
    WLBackend* b = w->be;
    struct wl_shm_pool* pool;
    int stride = width*4;
    size_t size = (size_t)stride * height;
    int fd;
    void* data;

    if ((width <= 0) || (height <= 0))
	return -1;
    if ((fd = create_shm_file(size)) < 0) {
	ERRORF("wayland: unable to create shm file: %s", strerror(errno));
	return -1;
    }
    data = mmap(NULL, size, PROT_READ|PROT_WRITE, MAP_SHARED, fd, 0);
    if (data == MAP_FAILED) {
	ERRORF("wayland: mmap failed: %s", strerror(errno));
	close(fd);
	return -1;
    }
    pool = wl_shm_create_pool(b->shm, fd, size);
    bp->buffer = wl_shm_pool_create_buffer(pool, 0, width, height, stride,
					   WL_SHM_FORMAT_XRGB8888);
    wl_shm_pool_destroy(pool);
    close(fd);
    wl_buffer_add_listener(bp->buffer, &buffer_listener, bp);
    bp->win    = w;
    bp->data   = data;
    bp->size   = size;
    bp->width  = width;
    bp->height = height;
    bp->stride = stride;
    bp->busy   = 0;
    bp->stale  = 0;
    return 0;
}

static void buffer_fill_white(WLBuffer* bp, int x0, int y0)
{
    int y;
    // fill area right of x0 and below y0 (outside copied area)
    for (y = 0; y < bp->height; y++) {
	uint8_t* row = bp->data + y*bp->stride;
	if (y >= y0)
	    memset(row, 0xff, bp->stride);
	else if (x0 < bp->width)
	    memset(row + x0*4, 0xff, (bp->width-x0)*4);
    }
}

// copy content from src to dst (overlapping area)
static void buffer_copy(WLBuffer* src, WLBuffer* dst)
{
    int w = (src->width < dst->width) ? src->width : dst->width;
    int h = (src->height < dst->height) ? src->height : dst->height;
    int y;
    for (y = 0; y < h; y++)
	memcpy(dst->data + y*dst->stride, src->data + y*src->stride, w*4);
    if ((w < dst->width) || (h < dst->height))
	buffer_fill_white(dst, w, h);
}

// destroy unused stale buffers
static void buffer_gc(WLWindow* w)
{
    int i;
    for (i = 0; i < WL_MAX_BUFFERS; i++) {
	WLBuffer* bp = &w->buf[i];
	if (bp->buffer && bp->stale && !bp->busy && (i != w->back)) {
	    buffer_destroy(bp);
	    if (w->front == i) w->front = -1;
	}
    }
}

static int buffer_ok(WLWindow* w, int i)
{
    WLBuffer* bp;
    if (i < 0) return 0;
    bp = &w->buf[i];
    return bp->buffer && !bp->stale &&
	(bp->width == w->width) && (bp->height == w->height);
}

// Get the buffer to draw into, the content is the latest content
static WLBuffer* get_back_buffer(WLWindow* w)
{
    int i, src, slot = -1;

    if (buffer_ok(w, w->back))
	return &w->buf[w->back];

    // content source: back (stale) else front
    src = (w->back >= 0 && w->buf[w->back].buffer) ? w->back : w->front;
    if (src >= 0 && !w->buf[src].buffer) src = -1;

    // fast path: front buffer released by compositor and correct size
    if ((src == w->front) && buffer_ok(w, w->front) &&
	!w->buf[w->front].busy) {
	w->back = w->front;
	buffer_gc(w);
	return &w->buf[w->back];
    }

    // find a free, correctly sized, buffer
    for (i = 0; i < WL_MAX_BUFFERS; i++) {
	if (i == src) continue;
	if (buffer_ok(w, i) && !w->buf[i].busy) { slot = i; break; }
    }
    if (slot < 0) {
	// find an empty slot (destroy stale non busy buffers first)
	for (i = 0; i < WL_MAX_BUFFERS; i++) {
	    WLBuffer* bp = &w->buf[i];
	    if (i == src) continue;
	    if (bp->buffer && bp->stale && !bp->busy) {
		buffer_destroy(bp);
		if (w->front == i) w->front = -1;
	    }
	    if (bp->buffer == NULL) {
		if (buffer_create(w, bp, w->width, w->height) < 0)
		    return NULL;
		slot = i;
		break;
	    }
	}
    }
    if (slot < 0) {
	// all buffers busy, draw into front buffer anyway (may tear)
	if (buffer_ok(w, w->front)) {
	    w->back = w->front;
	    return &w->buf[w->back];
	}
	WARNINGF("wayland: no buffer available");
	return NULL;
    }
    if (src >= 0)
	buffer_copy(&w->buf[src], &w->buf[slot]);
    else
	buffer_fill_white(&w->buf[slot], 0, 0);
    w->back = slot;
    buffer_gc(w);
    return &w->buf[slot];
}

static void add_damage(WLWindow* w, int x, int y, int width, int height)
{
    epx_rect_t r;
    epx_rect_set(&r, x, y, width, height);
    if (epx_rect_is_empty(&r))
	return;
    if (epx_rect_is_empty(&w->dirty))
	w->dirty = r;
    else
	epx_rect_union(&w->dirty, &r, &w->dirty);
}

// window size changed, mark all current buffers as stale
static void window_resize(WLWindow* w, int width, int height)
{
    int i;
    if ((width == w->width) && (height == w->height))
	return;
    w->width = width;
    w->height = height;
    w->ewin->area.wh.width = width;
    w->ewin->area.wh.height = height;
    for (i = 0; i < WL_MAX_BUFFERS; i++) {
	if (w->buf[i].buffer)
	    w->buf[i].stale = 1;
    }
    // create the new back buffer (copy old content) and request commit
    if (get_back_buffer(w)) {
	epx_rect_empty(&w->dirty);
	add_damage(w, 0, 0, width, height);
    }
}

/******************************************************************************
 *  frame callback & commit
 *****************************************************************************/

static void frame_done(void* data, struct wl_callback* cb, uint32_t time)
{
    WLWindow* w = (WLWindow*) data;
    (void) time;
    wl_callback_destroy(cb);
    if (w->frame_cb == cb)
	w->frame_cb = NULL;
    if (w->need_commit)
	do_commit(w);
}

static const struct wl_callback_listener frame_listener = {
    .done = frame_done
};

static void do_commit(WLWindow* w)
{
    WLBackend* b = w->be;
    WLBuffer* bp;

    w->need_commit = 0;
    if (!w->configured || w->hidden || (w->back < 0))
	return;
    bp = &w->buf[w->back];
    if (!bp->buffer)
	return;
    wl_surface_attach(w->surface, bp->buffer, 0, 0);
    if (epx_rect_is_empty(&w->dirty) || !w->mapped)
	epx_rect_set(&w->dirty, 0, 0, bp->width, bp->height);
    if (b->compositor_version >= 4)
	wl_surface_damage_buffer(w->surface,
				 w->dirty.xy.x, w->dirty.xy.y,
				 w->dirty.wh.width, w->dirty.wh.height);
    else
	wl_surface_damage(w->surface,
			  w->dirty.xy.x, w->dirty.xy.y,
			  w->dirty.wh.width, w->dirty.wh.height);
    if (w->frame_cb == NULL) {
	w->frame_cb = wl_surface_frame(w->surface);
	wl_callback_add_listener(w->frame_cb, &frame_listener, w);
    }
    wl_surface_commit(w->surface);
    bp->busy = 1;
    w->mapped = 1;
    w->front = w->back;
    w->back = -1;
    epx_rect_empty(&w->dirty);
    wl_display_flush(b->display);
}

static void window_swap(WLWindow* w)
{
    if (epx_rect_is_empty(&w->dirty) || (w->back < 0))
	return;
    if (w->frame_cb != NULL)   // wait for frame callback
	w->need_commit = 1;
    else
	do_commit(w);
}

